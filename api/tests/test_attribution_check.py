"""The required check `title` fails a pull request that credits an AI author."""

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "attribution_check.py"
TRAILER = "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
BADGE = "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=True
    ).stdout.strip()


@pytest.fixture
def repo(tmp_path):
    git(tmp_path, "init", "-q", "-b", "main")
    git(tmp_path, "config", "user.email", "t@example.com")
    git(tmp_path, "config", "user.name", "T")
    git(tmp_path, "commit", "-q", "--allow-empty", "-m", "chore: base\n\n" + TRAILER)
    return tmp_path


def commit(repo: Path, message: str) -> str:
    git(repo, "commit", "-q", "--allow-empty", "-m", message)
    return git(repo, "rev-parse", "--short", "HEAD")


def check(repo: Path, body: str | None = "", labels=(), revision_range="main..HEAD"):
    event = repo / "event.json"
    pull = {"body": body, "labels": [{"name": name} for name in labels]}
    event.write_text(json.dumps({"pull_request": pull}), encoding="utf-8")
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--event", str(event), revision_range],
        cwd=repo,
        capture_output=True,
        text=True,
    )


@pytest.fixture
def branch(repo):
    git(repo, "switch", "-q", "-c", "topic")
    return repo


def test_clean_commits_and_description_pass_and_the_base_is_not_read(branch):
    # The base commit carries a trailer; only the pull request's commits count.
    commit(branch, "feat: one\n\nBody that names the rule: no `Co-Authored-By:` line.")
    run = check(branch, body="## What Changed\n\nBlocks `Generated with` badges.")
    assert run.returncode == 0, run.stdout


def test_a_trailer_in_any_commit_fails_and_names_that_commit(branch):
    commit(branch, "feat: one")
    sha = commit(branch, "fix: two\n\n" + TRAILER.lower())
    run = check(branch)
    assert run.returncode == 1
    assert f"in {sha}:" in run.stdout and "co-authored-by" in run.stdout


@pytest.mark.parametrize(
    "body", [BADGE, "Generated with Codex", "text\n  Generated by Claude Code\n"]
)
def test_a_badge_in_the_description_fails(branch, body):
    commit(branch, "feat: one")
    run = check(branch, body=body)
    assert run.returncode == 1
    assert "in description:" in run.stdout


def test_the_label_lets_credit_maxi_asked_for_through(branch):
    commit(branch, "feat: one\n\n" + TRAILER)
    run = check(branch, body=BADGE, labels=("attribution-approved", "feature"))
    assert run.returncode == 0, run.stdout


def test_a_description_without_body_passes(branch):
    commit(branch, "feat: one")
    run = check(branch, body=None)
    assert run.returncode == 0, run.stdout + run.stderr


def test_a_range_git_cannot_read_fails_instead_of_passing(branch):
    run = check(branch, revision_range="nothere..HEAD")
    assert run.returncode != 0
